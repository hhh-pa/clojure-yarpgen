//! Test emitter: writes init/func/driver files plus an expected-hash
//! manifest per seed. Ports YARPGen's program.cpp emission
//! (init.h, func.c, driver.c).

use crate::cli::{CheckAlgo, Density, OnOff, Options, Std};
use crate::hash;
use crate::rng::Rng;
use crate::sexp::Sexp;
use crate::stmt::{self, Stmt};
use crate::types::{CType, Value};
use std::collections::BTreeSet;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// A generated input: never mutated, emitted as a plain `def`.
#[derive(Clone, Debug)]
pub struct Input {
    pub name: String,
    pub typ: CType,
    pub value: Value,
}

/// A generated output: emitted as an atom with an initial value, read
/// back at a final value the generator precomputed by simulation.
#[derive(Clone, Debug)]
pub struct Output {
    pub name: String,
    pub init: i64,
    pub final_value: i64,
}

/// One complete generated program.
#[derive(Clone, Debug)]
pub struct Program {
    pub seed: u64,
    pub inputs: Vec<Input>,
    pub outputs: Vec<Output>,
    pub stmts: Vec<Stmt>,
    pub expected_hash: i64,
    pub check_algo: CheckAlgo,
}

impl Program {
    pub fn sorted_outputs(&self) -> Vec<&Output> {
        let mut v: Vec<&Output> = self.outputs.iter().collect();
        v.sort_by(|a, b| a.name.cmp(&b.name));
        v
    }
}

pub struct EmitPaths {
    pub init: PathBuf,
    pub func: PathBuf,
    pub driver: PathBuf,
    pub expected: PathBuf,
}

/// Maximum cost units per emitted function (see `stats::stmt_cost`).
/// Top-level statements are chunked into sequential `test-fn-N`
/// functions so no single method nears the 64KB JVM limit.
pub const MAX_FN_COST: u64 = 60;
/// Maximum cost units for a single top-level statement. Statements
/// past this bar cannot be chunked further, so generation repopulates
/// (mutation retries) instead of emitting them.
pub const MAX_STMT_COST: u64 = 150;

/// Output file paths for a test directory and dialect.
pub fn output_paths(out_dir: &Path, std: Std) -> EmitPaths {
    let ext = extension(std);
    EmitPaths {
        init: out_dir.join(format!("init.{ext}")),
        func: out_dir.join(format!("func.{ext}")),
        driver: out_dir.join(format!("driver.{ext}")),
        expected: out_dir.join("expected.edn"),
    }
}

fn extension(std: Std) -> &'static str {
    match std {
        Std::Clj => "clj",
        Std::Cljs => "cljs",
        Std::Cljc => "cljc",
    }
}

fn options_summary(o: &Options) -> String {
    format!(
        "std={:?} check-algo={:?} emit-pragmas={:?} param-shuffle={} expl-loop-param={} mutate={:?} allow-exc-in-dead={:?} simple-loops={:?} unchecked-math={:?}",
        o.std,
        o.check_algo,
        o.emit_pragmas,
        o.param_shuffle,
        o.expl_loop_param,
        o.mutate,
        o.allow_exc_in_dead,
        o.simple_loops,
        o.unchecked_math
    )
}

fn header_comment(seed: u64, options: &Options) -> String {
    format!(
        ";; Generated by clojure-yarpgen, seed {seed}\n;; Options: {}\n",
        options_summary(options)
    )
}

fn dg_header(check_algo: CheckAlgo) -> &'static str {
    match check_algo {
        CheckAlgo::Asserts => {
            ";; { dg-do run }\n;; { dg-mode interp+aot }\n;; { dg-output \"TORTURE-PASS\" }\n"
        }
        CheckAlgo::Hash => {
            ";; { dg-do run }\n;; { dg-mode interp+aot }\n;; { dg-output-re \"^-?[0-9]+ [0-9]+$\" }\n"
        }
    }
}

fn roll_hint(rng: &mut Rng, mode: Density) -> bool {
    match mode {
        Density::All => true,
        Density::Some => rng.roll(0.5),
        Density::None => false,
    }
}

/// Walk emitted body forms, hinting `doseq` binding symbols per roll.
fn hint_loops(form: Sexp, rng: &mut Rng, mode: Density) -> Sexp {
    match form {
        Sexp::List(items) => {
            if items.first() == Some(&Sexp::sym("doseq")) && items.len() >= 3 {
                let mut items = items;
                if let Sexp::List(bind) = &items[1] {
                    if bind.len() == 3 {
                        if let Sexp::Sym(name) = &bind[1] {
                            let name = name.clone();
                            let hinted = if roll_hint(rng, mode) {
                                Sexp::Hinted(name)
                            } else {
                                Sexp::sym(&name)
                            };
                            let mut new_bind = bind.clone();
                            new_bind[1] = hinted;
                            items[1] = Sexp::List(new_bind);
                        }
                    }
                }
                let rest: Vec<Sexp> = items[2..]
                    .iter()
                    .cloned()
                    .map(|f| hint_loops(f, rng, mode))
                    .collect();
                let mut out = items[..2].to_vec();
                out.extend(rest);
                Sexp::List(out)
            } else {
                Sexp::List(
                    items
                        .into_iter()
                        .map(|f| hint_loops(f, rng, mode))
                        .collect(),
                )
            }
        }
        other => other,
    }
}

fn init_forms(program: &Program) -> Vec<Sexp> {
    // Note: no type hints on defs. A ^long hint on a def breaks every
    // later use of the var ("Unable to resolve classname"), as probed
    // against clojure 1.12. Hints are emitted on doseq bindings only.
    let mut forms = vec![Sexp::list(vec![Sexp::sym("ns"), Sexp::sym("gen-init")])];
    for input in &program.inputs {
        let form = match &input.value {
            Value::Vec(items) => Sexp::list(vec![
                Sexp::sym("def"),
                Sexp::sym(&input.name),
                Sexp::vec(items.iter().map(|n| Sexp::int(*n)).collect()),
            ]),
            Value::Bool(b) => Sexp::list(vec![
                Sexp::sym("def"),
                Sexp::sym(&input.name),
                Sexp::bool(*b),
            ]),
            Value::Long(n) => Sexp::list(vec![
                Sexp::sym("def"),
                Sexp::sym(&input.name),
                Sexp::int(*n),
            ]),
        };
        forms.push(form);
    }
    forms
}

/// Greedily chunk top-level statements into per-function groups.
/// Chunks split only between top-level statements, so loop variables
/// never escape and sequential calls preserve semantics exactly.
fn chunk_stmts(stmts: &[Stmt]) -> Vec<&[Stmt]> {
    let mut chunks = Vec::new();
    let mut start = 0;
    let mut cost = 0;
    for (i, s) in stmts.iter().enumerate() {
        let c = crate::stats::stmt_cost(s);
        if cost > 0 && cost + c > MAX_FN_COST {
            chunks.push(&stmts[start..i]);
            start = i;
            cost = 0;
        }
        cost += c;
    }
    if start < stmts.len() || chunks.is_empty() {
        chunks.push(&stmts[start..]);
    }
    chunks
}

fn func_forms(program: &Program, rng: &mut Rng, options: &Options) -> Vec<Sexp> {
    let atoms: BTreeSet<String> = program.outputs.iter().map(|o| o.name.clone()).collect();
    let mut forms = vec![Sexp::list(vec![
        Sexp::sym("ns"),
        Sexp::sym("gen-func"),
        Sexp::list(vec![
            Sexp::sym(":require"),
            Sexp::vec(vec![
                Sexp::sym("gen-init"),
                Sexp::sym(":refer"),
                Sexp::sym(":all"),
            ]),
        ]),
    ])];
    if options.unchecked_math == OnOff::On {
        forms.push(Sexp::list(vec![
            Sexp::sym("set!"),
            Sexp::sym("*unchecked-math*"),
            Sexp::bool(true),
        ]));
    }
    for o in program.sorted_outputs() {
        forms.push(Sexp::list(vec![
            Sexp::sym("def"),
            Sexp::sym(&o.name),
            Sexp::list(vec![Sexp::sym("atom"), Sexp::int(o.init)]),
        ]));
    }
    let chunks = chunk_stmts(&program.stmts);
    if chunks.len() == 1 {
        let mut body = vec![Sexp::vec(vec![])];
        for s in chunks[0] {
            body.push(hint_loops(
                stmt::to_sexp(s, &atoms),
                rng,
                options.emit_pragmas,
            ));
        }
        let mut test_fn = vec![Sexp::sym("defn"), Sexp::sym("test-fn")];
        test_fn.extend(body);
        forms.push(Sexp::list(test_fn));
    } else {
        for (k, chunk) in chunks.iter().enumerate() {
            let mut body = vec![Sexp::vec(vec![])];
            for s in *chunk {
                body.push(hint_loops(
                    stmt::to_sexp(s, &atoms),
                    rng,
                    options.emit_pragmas,
                ));
            }
            let mut f = vec![Sexp::sym("defn"), Sexp::sym(&format!("test-fn-{k}"))];
            f.extend(body);
            forms.push(Sexp::list(f));
        }
        let mut dispatch = vec![Sexp::sym("defn"), Sexp::sym("test-fn"), Sexp::vec(vec![])];
        for k in 0..chunks.len() {
            dispatch.push(Sexp::list(vec![Sexp::sym(&format!("test-fn-{k}"))]));
        }
        forms.push(Sexp::list(dispatch));
    }
    let outs: Vec<Sexp> = program
        .sorted_outputs()
        .iter()
        .map(|o| Sexp::list(vec![Sexp::sym("deref"), Sexp::sym(&o.name)]))
        .collect();
    forms.push(Sexp::list(vec![
        Sexp::sym("defn"),
        Sexp::sym("outputs"),
        Sexp::vec(vec![]),
        Sexp::vec(outs),
    ]));
    forms
}

fn driver_forms(program: &Program) -> Vec<Sexp> {
    let mut forms = vec![Sexp::list(vec![
        Sexp::sym("ns"),
        Sexp::sym("gen-driver"),
        Sexp::list(vec![
            Sexp::sym(":require"),
            Sexp::vec(vec![Sexp::sym("gen-func")]),
        ]),
    ])];
    let main = match program.check_algo {
        CheckAlgo::Asserts => {
            let expected: Vec<Sexp> = program
                .sorted_outputs()
                .iter()
                .map(|o| Sexp::int(o.final_value))
                .collect();
            Sexp::list(vec![
                Sexp::sym("defn"),
                Sexp::sym("-main"),
                Sexp::vec(vec![Sexp::sym("&"), Sexp::sym("_")]),
                Sexp::list(vec![Sexp::sym("gen-func/test-fn")]),
                Sexp::list(vec![
                    Sexp::sym("let"),
                    Sexp::vec(vec![
                        Sexp::sym("actual"),
                        Sexp::list(vec![Sexp::sym("gen-func/outputs")]),
                        Sexp::sym("expected"),
                        Sexp::vec(expected),
                    ]),
                    Sexp::list(vec![
                        Sexp::sym("if"),
                        Sexp::list(vec![
                            Sexp::sym("="),
                            Sexp::sym("actual"),
                            Sexp::sym("expected"),
                        ]),
                        Sexp::list(vec![Sexp::sym("println"), Sexp::str("TORTURE-PASS")]),
                        Sexp::list(vec![
                            Sexp::sym("println"),
                            Sexp::str("ERROR: value mismatch"),
                        ]),
                    ]),
                ]),
            ])
        }
        CheckAlgo::Hash => Sexp::list(vec![
            Sexp::sym("defn"),
            Sexp::sym("-main"),
            Sexp::vec(vec![Sexp::sym("&"), Sexp::sym("_")]),
            Sexp::list(vec![Sexp::sym("gen-func/test-fn")]),
            Sexp::list(vec![
                Sexp::sym("println"),
                hash::checksum_sexp(),
                Sexp::int(program.seed as i64),
            ]),
        ]),
    };
    forms.push(main);
    forms
}

fn write_forms(path: &Path, header: &str, dg: Option<&str>, forms: &[Sexp]) -> io::Result<()> {
    let mut out = String::from(header);
    if let Some(dg) = dg {
        out.push_str(dg);
    }
    for f in forms {
        out.push_str(&f.pretty());
        out.push_str("\n\n");
    }
    fs::write(path, out)
}

/// Write init/func/driver files plus the `expected.edn` manifest.
pub fn emit_test(
    out_dir: &Path,
    program: &Program,
    options: &Options,
    rng: &mut Rng,
) -> io::Result<()> {
    fs::create_dir_all(out_dir)?;
    let paths = output_paths(out_dir, options.std);
    let header = header_comment(program.seed, options);
    let dg = options.dg_headers.then(|| dg_header(program.check_algo));
    write_forms(&paths.init, &header, dg, &init_forms(program))?;
    write_forms(&paths.func, &header, dg, &func_forms(program, rng, options))?;
    write_forms(&paths.driver, &header, dg, &driver_forms(program))?;
    fs::write(
        &paths.expected,
        format!(
            "{{:seed {} :expected-hash {} :check-algo :{}}}\n",
            program.seed,
            program.expected_hash,
            match program.check_algo {
                CheckAlgo::Hash => "hash",
                CheckAlgo::Asserts => "asserts",
            }
        ),
    )?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::stmt::Stmt;
    use crate::types::Ir;

    fn sample_program() -> Program {
        Program {
            seed: 42,
            inputs: vec![Input {
                name: "in-0".to_string(),
                typ: CType::Long,
                value: Value::Long(3),
            }],
            outputs: vec![Output {
                name: "out-0".to_string(),
                init: 0,
                final_value: 4,
            }],
            stmts: vec![Stmt::Assign {
                target: "out-0".to_string(),
                expr: crate::expr::Expr::Const(Ir::long(4)),
            }],
            expected_hash: 123,
            check_algo: CheckAlgo::Hash,
        }
    }

    #[test]
    fn emits_three_files_and_manifest() {
        let dir = std::env::temp_dir().join("cy-emit-test");
        let _ = fs::remove_dir_all(&dir);
        let mut rng = Rng::new(1);
        let options = Options::default();
        emit_test(&dir, &sample_program(), &options, &mut rng).unwrap();
        let res = output_paths(&dir, options.std);
        for p in [&res.init, &res.func, &res.driver, &res.expected] {
            assert!(p.exists(), "missing {}", p.display());
        }
        let manifest = fs::read_to_string(&res.expected).unwrap();
        assert!(manifest.contains(":expected-hash 123"));
        let driver = fs::read_to_string(&res.driver).unwrap();
        assert!(driver.contains("gen-driver"));
        assert!(driver.contains("seed 42"));
        let _ = fs::remove_dir_all(&dir);
    }

    fn contains_hinted(form: &Sexp) -> bool {
        match form {
            Sexp::Hinted(_) => true,
            Sexp::List(items) => items.iter().any(contains_hinted),
            _ => false,
        }
    }

    #[test]
    fn hints_never_appear_on_defs() {
        // A ^long hint on a def breaks every later use of the var
        // ("Unable to resolve classname" on clojure 1.12); hints may
        // only appear on doseq bindings.
        let program = sample_program();
        for form in init_forms(&program) {
            assert!(!contains_hinted(&form), "hint on init def: {}", form.flat());
        }
        for form in func_forms(&program, &mut Rng::new(1), &Options::default()) {
            if let Sexp::List(items) = &form {
                if items.first() == Some(&Sexp::sym("def")) {
                    assert!(!contains_hinted(&form), "hint on func def: {}", form.flat());
                }
            }
        }
    }

    #[test]
    fn asserts_driver_checks_values() {
        let mut p = sample_program();
        p.check_algo = CheckAlgo::Asserts;
        let forms = driver_forms(&p);
        let flat = forms
            .iter()
            .map(|f| f.flat())
            .collect::<Vec<_>>()
            .join("\n");
        assert!(flat.contains("TORTURE-PASS"));
        assert!(flat.contains("value mismatch"));
    }
}
